<#
  Cai cong cu Zalo (MCP) chay thuong truc tren Windows.

  - Chay "zalo-agent mcp start --http <port> --auth <ma>" an (khong cua so), tu bat khi dang nhap Windows,
    tu chay lai sau 1 phut neu bi loi (Task Scheduler, ten task: ZaloAgentMCP).
  - Doi Claude Code tu "tu bat ban rieng" (stdio) sang "noi vao dich vu" (HTTP) de chi co MOT phien Zalo.

  Chay trong PowerShell (Run as administrator), tu thu muc repo:
      powershell -ExecutionPolicy Bypass -File .\scripts\windows\install-service.ps1
  Go bo: .\scripts\windows\uninstall-service.ps1
  (File chi dung chu ASCII de Windows PowerShell 5.1 doc dung.)
#>
param(
    [int]$Port = 3847,
    [string]$TaskName = "ZaloAgentMCP",
    # Thu muc du lieu (dang nhap Zalo, mcp-config.json, log). Mac dinh: $env:ZALO_AGENT_HOME hoac ~\.zalo-agent-cli
    [string]$DataDir = $(if ($env:ZALO_AGENT_HOME) { $env:ZALO_AGENT_HOME } else { Join-Path $HOME ".zalo-agent-cli" })
)
$ErrorActionPreference = "Stop"

$repo = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$entry = Join-Path $repo "src\index.js"
if (-not (Test-Path $entry)) { throw "Khong thay $entry - chay script tu repo zalo-agent-cli." }

$node = (Get-Command node -ErrorAction Stop).Source
$cfgDir = $DataDir
$svcDir = Join-Path $cfgDir "service"
New-Item -ItemType Directory -Force -Path $svcDir | Out-Null

# 1. Ma truy cap HTTP: tao moi neu chua co, chi chu tai khoan doc duoc
$tokenFile = Join-Path $svcDir "http-token.txt"
if (-not (Test-Path $tokenFile)) {
    $tok = [guid]::NewGuid().ToString("N") + [guid]::NewGuid().ToString("N")
    [System.IO.File]::WriteAllText($tokenFile, $tok)
}
$token = ([System.IO.File]::ReadAllText($tokenFile)).Trim()
icacls $tokenFile /inheritance:r /grant:r "$($env:USERNAME):F" | Out-Null

# 2. Launcher an cua so: wscript chay node qua cmd, ghi log, cho node ket thuc va tra ma loi
$log = Join-Path $svcDir "mcp-http.log"
$vbs = Join-Path $svcDir "run-hidden.vbs"
$cmdLine = "cmd /c """"$node"" ""$entry"" mcp start --http $Port --auth $token >> ""$log"" 2>&1"""
$vbsCmd = $cmdLine.Replace('"', '""')
$vbsText = @"
' Generated by install-service.ps1 - do not share (contains the MCP HTTP token)
Set sh = CreateObject("WScript.Shell")
sh.Environment("PROCESS")("ZALO_AGENT_HOME") = "$cfgDir"
rc = sh.Run("$vbsCmd", 0, True)
WScript.Quit rc
"@
[System.IO.File]::WriteAllText($vbs, $vbsText)
icacls $vbs /inheritance:r /grant:r "$($env:USERNAME):F" | Out-Null

# 3. Dung ban dang chay (task cu, hoac ban Claude Code tu bat) de khong gianh phien Zalo
if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
    Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
}
Get-CimInstance Win32_Process -Filter "name='node.exe'" |
    Where-Object { $_.CommandLine -like "*mcp start*" } |
    ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }

# 4. Task Scheduler: khi dang nhap, chay lai sau 1 phut neu loi, khong gioi han thoi gian
$user = "$env:USERDOMAIN\$env:USERNAME"
$action = New-ScheduledTaskAction -Execute "wscript.exe" -Argument """$vbs"""
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $user
$principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
    -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit ([TimeSpan]::Zero) `
    -MultipleInstances IgnoreNew
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Principal $principal `
    -Settings $settings -Description "zalo-agent-cli MCP (HTTP 127.0.0.1:$Port) - always on" -Force | Out-Null
Start-ScheduledTask -TaskName $TaskName

# 5. Cho dich vu len
$health = "http://127.0.0.1:$Port/health"
$ok = $false
for ($i = 0; $i -lt 30; $i++) {
    Start-Sleep -Seconds 2
    try { $h = Invoke-RestMethod -Uri $health -TimeoutSec 3; if ($h.status -eq "ok") { $ok = $true; break } } catch {}
}
if (-not $ok) {
    Write-Host "Dich vu chua len sau 60 giay. Xem log: $log" -ForegroundColor Red
    if (Test-Path $log) { Get-Content $log -Tail 20 }
    exit 1
}
Write-Host "Dich vu dang chay: $health" -ForegroundColor Green

# 6. Noi Claude Code vao dich vu (thay cho ban stdio tu bat)
# Lenh ngoai (claude) ghi stderr khi khong co server cu: khong coi la loi
$ErrorActionPreference = "Continue"
if (Get-Command claude -ErrorAction SilentlyContinue) {
    claude mcp remove zalo -s user 2>$null | Out-Null
    claude mcp add --transport http zalo "http://127.0.0.1:$Port/mcp" --header "Authorization: Bearer $token" -s user | Out-Null
    claude mcp get zalo
} else {
    Write-Host "Khong thay lenh 'claude'. Tu chay:" -ForegroundColor Yellow
    Write-Host "  claude mcp remove zalo -s user"
    Write-Host "  claude mcp add --transport http zalo http://127.0.0.1:$Port/mcp --header ""Authorization: Bearer <ma trong $tokenFile>"" -s user"
}
Write-Host ""
Write-Host "Xong. Log: $log" -ForegroundColor Green
Write-Host "Mo phien Claude Code moi de dung. Khong chay tay 'zalo-agent mcp start' nua."
